// Build small, immutable question files from the same verified full bank.
const fs = require('node:fs');
const vm = require('node:vm');
const crypto = require('node:crypto');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({window:{}});
for (const file of ['coverage-bank-data.js','question-engine.js','learning-summary.js']) vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context);
const bank = context.window.EnglishRoadQuestions.createQuestionBank();
const revision = context.window.EnglishRoadQuestions.bankRevision(bank);
const directory = path.join(root,'data','questions');
const groups = [];
const outputs = new Map();
for (let offset=0;offset<bank.length;offset+=20) {
  const items=bank.slice(offset,offset+20);
  const body=JSON.stringify(items)+'\n';
  const hash=crypto.createHash('sha256').update(body).digest('hex');
  const first=items[0];
  const file=`data/questions/${first.blueprint}-${hash.slice(0,16)}.json`;
  groups.push({code:first.blueprint,category:first.category,subcategory:first.subcategory,difficulty:first.difficulty,start:offset+1,count:items.length,file,hash});
  outputs.set(file,body);
}
outputs.set('bank-index.js',`// Generated by scripts/split-question-bank.cjs.\nwindow.EnglishRoadBankIndex = ${JSON.stringify({revision,count:bank.length,groups})};\n`);
const check=process.argv.includes('--check');
if(!check) {fs.mkdirSync(directory,{recursive:true}); for(const file of fs.readdirSync(directory)) if(!outputs.has(`data/questions/${file}`)) fs.unlinkSync(path.join(directory,file));}
for(const [file,body] of outputs) {
  const dest=path.join(root,file);
  if(check) {if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==body) throw new Error(`Rebuild question files: ${file}`);}
  else fs.writeFileSync(dest,body);
}
console.log(`Verified ${bank.length} questions in ${groups.length} small files; revision ${revision}.`);
